test('timer pause holds remaining time and resume continues from that value', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-09-24T12:00:00') })
  await page.goto('/#/timer')
  await page.getByRole('button', { name: /Start/ }).click()
  await page.clock.fastForward(30_000)
  await page.getByRole('button', { name: /Pause/ }).click()
  const paused = await page.locator('.timer-digits span').textContent()
  await page.clock.fastForward(60_000)
  await expect(page.locator('.timer-digits span')).toHaveText(paused!)
  await page.getByRole('button', { name: /Start/ }).click()
  const resumed = await page.locator('.timer-digits span').textContent()
  await page.clock.fastForward(10_000)
  const afterResume = await page.locator('.timer-digits span').textContent()
  const asSeconds = (value: string) => { const [minutes, seconds] = value.split(':').map(Number); return minutes * 60 + seconds }
  expect(asSeconds(resumed!)-asSeconds(afterResume!)).toBeGreaterThanOrEqual(9)
  expect(asSeconds(resumed!)-asSeconds(afterResume!)).toBeLessThanOrEqual(11)
})

