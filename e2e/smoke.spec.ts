test('countdown editor is accessible and traps keyboard focus', async ({ page }) => {
  await page.goto('/#/countdown')
  const opener = page.getByRole('button', { name: /New countdown/ })
  await opener.click()
  const dialog = page.getByRole('dialog')
  const results = await new AxeBuilder({ page }).analyze()
  expect(results.violations.filter(v => v.impact === 'critical' || v.impact === 'serious').map(v => v.id)).toEqual([])
  await page.getByRole('button', { name: 'Save countdown' }).focus()
  await expect(page.getByRole('button', { name: 'Save countdown' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Close' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.getByRole('button', { name: 'Save countdown' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  await page.goto('/#/settings')
  await page.getByRole('combobox').selectOption('dark')
  const darkResults = await new AxeBuilder({ page }).analyze()
  expect(darkResults.violations.filter(v => v.impact === 'critical' || v.impact === 'serious').map(v => v.id)).toEqual([])
})

